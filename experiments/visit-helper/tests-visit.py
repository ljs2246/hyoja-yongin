# 병원 방문 도우미 모의 브라우저 시험 — 실기기(Android/iPhone) 시험이 아님
import sys, pathlib, json
from playwright.sync_api import sync_playwright
root = pathlib.Path(__file__).parent.resolve()
shots = pathlib.Path(sys.argv[1]) if len(sys.argv)>1 else root/"shots"
shots.mkdir(parents=True, exist_ok=True)
res=[]; errs=[]; reqs=[]
def ok(n,c): res.append((n,bool(c))); print(("통과 " if c else "실패 ")+n)
URL=(root/"index.html").as_uri()
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={"width":390,"height":844}); pg=ctx.new_page()
    pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("request",lambda r:reqs.append(r.url))
    pg.goto(URL)
    pg.evaluate("localStorage.setItem('hyoja-family', JSON.stringify([{name:'큰딸',phone:'010-1234-5678'}]))")
    pg.reload()
    pg.screenshot(path=str(shots/"1_main.png"),full_page=True)
    ok("메인에 병원 연동 없음 안내", "연결되어 있지 않아요" in pg.inner_text("#app"))
    ok("메인 4단계 + 가상 화면 링크", pg.locator("a.step").count()==4 and pg.locator("a[href*='demo.html']").count()==2)
    # 1 병원 가기 전
    pg.click("a.step >> nth=0")
    pg.fill("#hn","우리동네의원"); pg.fill("#hp","031-123-4567")
    ok("네이버 지도 링크 생성", pg.get_attribute("#mapB","href").startswith("https://map.naver.com/p/search/"))
    ok("병원 전화 링크 tel:", pg.get_attribute("#telB","href")=="tel:0311234567")
    pg.fill("#hp","abc"); ok("잘못된 전화번호는 링크 막고 안내", pg.get_attribute("#telB","href").endswith("#") and "맞지 않아요" in pg.inner_text("#hpMsg"))
    pg.fill("#vd","2026-11-05"); pg.fill("#vt","10:30")
    ok("가족에게 문자 링크(사용자가 직접 전송)", "sms:01012345678" in pg.get_attribute("#famBox a","href"))
    pg.screenshot(path=str(shots/"2_prep.png"),full_page=True)
    # 2 접수번호
    pg.goto(URL+"#/ticket"); pg.fill("#tn","a-023")
    ok("접수번호 대문자 저장·큰 글씨 표시", pg.inner_text("#show .bignum")=="A-023" and pg.evaluate("parseFloat(getComputedStyle(document.querySelector('#show .bignum')).fontSize)")>=48)
    ok("직접 적은 번호라는 경고 표시", "직접 적은 번호" in pg.inner_text("#app"))
    pg.fill("#tn","홍길동"); ok("이름 같은 값 거부", "쓸 수 있어요" in pg.inner_text("#tmsg"))
    pg.fill("#tn","A-023")
    jpg=pg.screenshot(type="jpeg"); (shots/"fake.jpg").write_bytes(jpg)
    pg.set_input_files("#ph",str(shots/"fake.jpg")); pg.wait_for_selector("img.photo",timeout=5000)
    ok("번호표 사진 기기 내 저장", pg.locator("img.photo").count()==1 and "서버로 보내지 않아요" in pg.inner_text("#pmsg"))
    pg.reload(); ok("새로고침 후에도 번호·사진 유지", pg.inner_text("#show .bignum")=="A-023" and pg.locator("img.photo").count()==1)
    pg.screenshot(path=str(shots/"3_ticket.png"),full_page=True)
    pg.click("#phDel"); ok("사진 삭제", pg.locator("img.photo").count()==0 and pg.evaluate("!JSON.parse(localStorage.getItem('hj_visit_v1')).photo"))
    # 3 대기 알림
    pg.goto(URL+"#/wait")
    ok("병원 호출이 아니라는 표시", "병원의 호출 알림이 아니에요" in pg.inner_text("#app"))
    pg.select_option("#mins","5"); pg.click("#setB")
    ok("카운트다운 표시", "알림까지" in pg.inner_text("#cd"))
    pg.screenshot(path=str(shots/"4_wait.png"),full_page=True)
    pg.evaluate("(()=>{const o=JSON.parse(localStorage.getItem('hj_visit_v1'));o.dueAt=Date.now()-1000;localStorage.setItem('hj_visit_v1',JSON.stringify(o));})()")
    pg.reload(); pg.wait_for_timeout(1200)
    ok("시간이 되면 알림 문구(병원 호출 아님 표시)", pg.locator("#alarm").is_visible() and "병원 호출이 아니에요" in pg.inner_text("#alarm"))
    pg.screenshot(path=str(shots/"4b_wait_alarm.png"),full_page=True)
    pg.click("#offB"); ok("알림 끄기", not pg.locator("#alarm").is_visible())
    pg.click("#helpB"); ok("직원 도움 요청 카드에 접수번호", "A-023" in pg.inner_text("#help"))
    ok("가족 전화 tel 링크", pg.locator("a[href='tel:01012345678']").count()>=1)
    # 4~5 가상 대기판/카드
    pg.goto(URL); pg.click("a[href*='demo.html#staff']"); pg.wait_for_selector("#staff")
    ok("가상 직원 대기판 열림(가상 안내)", "가상" in pg.inner_text(".banner") and pg.locator("#staff").is_visible())
    pg.screenshot(path=str(shots/"5_staff.png"),full_page=True)
    pg.locator("button[aria-label='A-023 수정']").click(); pg.fill("#ahead","3"); pg.click("#apply")
    pg.click("#tabP"); pg.select_option("#mine",label="A-023")
    ok("가상 환자 카드에 직원 확정 인원 표시", pg.inner_text("#pAhead")=="3")
    pg.screenshot(path=str(shots/"6_card.png"),full_page=True)
    pg.goto("file://"+str(root.parent/"hospital-queue"/"demo.html")+"#patient")
    ok("#patient 주소로 바로 환자 화면", pg.locator("#patient").is_visible())
    # 6 진료 후
    pg.goto(URL+"#/pharmacy"); pg.fill("#hm","용인 가상아파트")
    ok("약국 지도 링크 + 집 길찾기 링크", pg.locator("a[href*='map.naver.com/p/search/%EC%95%BD%EA%B5%AD']").count()==1 and "map.naver.com/p/search/" in pg.get_attribute("#hmB","href"))
    ok("처방전 저장 기능 없음 명시", "저장하지 않아요" in pg.inner_text("#app"))
    pg.screenshot(path=str(shots/"7_pharmacy.png"),full_page=True)
    # 공통
    for r in ["home","prep","ticket","wait","pharmacy"]:
        pg.goto(URL+"#/"+r)
        small=pg.evaluate("[...document.querySelectorAll('a.btn,button.btn,a.home,a.step,input,select')].filter(e=>e.offsetParent).filter(e=>e.getBoundingClientRect().height<48).length")
        scroll=pg.evaluate("document.documentElement.scrollWidth>window.innerWidth")
        ok(f"{r}: 누를 곳 48px 이상·가로 스크롤 없음", small==0 and not scroll)
    body=" ".join(pg.inner_text("#app") for _ in [0])
    bad=[u for u in reqs if not u.startswith("file://") and not u.startswith("data:")]
    ok("외부 서버 요청 0건(지도·전화 링크는 눌러야만 열림)", not bad)
    ctx.close(); b.close()
ok("자바스크립트 오류 0건", not errs)
f=[n for n,c in res if not c]; print(f"\n{len(res)-len(f)}/{len(res)} 통과", errs, bad if 'bad' in dir() else "")
sys.exit(1 if f else 0)
